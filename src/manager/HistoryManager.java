package manager;

import tasks.Task;
import java.util.List;

/**
 * Интерфейс для управления историей просмотров задач.
 * Позволяет добавлять задачи в историю, удалять их и получать список просмотренных задач.
 * История не имеет ограничения по размеру и не содержит дубликатов.
 *
 * @author Kirill-Kazantcev
 * @version 3.0
 * @since Sprint 6
 */
public interface HistoryManager {

    /**
     * Помечает задачу как просмотренную и добавляет её в историю.
     * Если задача уже есть в истории, предыдущий просмотр удаляется,
     * а задача добавляется в конец списка (обновление позиции).
     * Время выполнения - O(1).
     *
     * @param task задача, которую нужно добавить в историю
     */
    void add(Task task);

    /**
     * Удаляет задачу из истории просмотров по её идентификатору.
     * Время выполнения - O(1).
     *
     * @param id идентификатор задачи для удаления
     */
    void remove(int id);

    /**
     * Полностью очищает всю историю просмотров.
     * Удаляет все задачи из истории.
     * Время выполнения - O(1).
     */
    void clear();

    /**
     * Возвращает список просмотренных задач в порядке их просмотра.
     * Последние просмотренные задачи находятся в конце списка.
     * Время выполнения - O(n), где n - размер истории.
     *
     * @return список задач в порядке просмотра
     */
    List<Task> getHistory();
}