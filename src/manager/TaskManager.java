package manager;

import tasks.Task;
import tasks.Epic;
import tasks.Subtask;
import java.util.List;

/**
 * Интерфейс менеджера задач.
 * Определяет контракт для управления задачами всех типов:
 * обычными задачами, эпиками и подзадачами.
 *
 * @author Kirill-Kazantcev
 * @version 3.0
 * @since Sprint 5
 */
public interface TaskManager {

    // ========== Методы для обычных задач (Task) ==========

    /**
     * Возвращает список всех обычных задач.
     *
     * @return список всех обычных задач
     */
    List<Task> getTasks();

    /**
     * Удаляет все обычные задачи.
     * Также удаляет задачи из истории просмотров.
     */
    void deleteAllTasks();

    /**
     * Возвращает задачу по её идентификатору.
     * При вызове задача добавляется в историю просмотров.
     *
     * @param id идентификатор задачи
     * @return задача с указанным ID или null, если задача не найдена
     */
    Task getTask(int id);

    /**
     * Создаёт новую задачу.
     * Присваивает задаче уникальный идентификатор.
     *
     * @param task создаваемая задача
     * @return созданная задача с присвоенным ID
     * @throws IllegalArgumentException если задача равна null
     */
    Task createTask(Task task);

    /**
     * Обновляет существующую задачу.
     *
     * @param task задача с обновлёнными данными
     * @throws IllegalArgumentException если задача равна null или задача с таким ID не существует
     */
    void updateTask(Task task);

    /**
     * Удаляет задачу по идентификатору.
     * Также удаляет задачу из истории просмотров.
     *
     * @param id идентификатор удаляемой задачи
     */
    void deleteTask(int id);

    // ========== Методы для эпиков (Epic) ==========

    /**
     * Возвращает список всех эпиков.
     *
     * @return список всех эпиков
     */
    List<Epic> getEpics();

    /**
     * Удаляет все эпики и их подзадачи.
     * Также удаляет эпики и подзадачи из истории просмотров.
     */
    void deleteAllEpics();

    /**
     * Возвращает эпик по его идентификатору.
     * При вызове эпик добавляется в историю просмотров.
     *
     * @param id идентификатор эпика
     * @return эпик с указанным ID или null, если эпик не найден
     */
    Epic getEpic(int id);

    /**
     * Создаёт новый эпик.
     * Присваивает эпику уникальный идентификатор.
     *
     * @param epic создаваемый эпик
     * @return созданный эпик с присвоенным ID
     * @throws IllegalArgumentException если эпик равен null
     */
    Epic createEpic(Epic epic);

    /**
     * Обновляет название и описание эпика.
     * Статус эпика не обновляется, так как рассчитывается автоматически на основе подзадач.
     *
     * @param epic эпик с обновлёнными данными
     * @throws IllegalArgumentException если эпик равен null или эпик с таким ID не существует
     */
    void updateEpic(Epic epic);

    /**
     * Удаляет эпик и все его подзадачи.
     * Также удаляет эпик и подзадачи из истории просмотров.
     *
     * @param id идентификатор удаляемого эпика
     */
    void deleteEpic(int id);

    // ========== Методы для подзадач (Subtask) ==========

    /**
     * Возвращает список всех подзадач.
     *
     * @return список всех подзадач
     */
    List<Subtask> getSubtasks();

    /**
     * Удаляет все подзадачи и обновляет статусы эпиков.
     * Также удаляет подзадачи из истории просмотров.
     */
    void deleteAllSubtasks();

    /**
     * Возвращает подзадачу по её идентификатору.
     * При вызове подзадача добавляется в историю просмотров.
     *
     * @param id идентификатор подзадачи
     * @return подзадача с указанным ID или null, если подзадача не найдена
     */
    Subtask getSubtask(int id);

    /**
     * Создаёт новую подзадачу с проверкой существования эпика.
     *
     * @param subtask создаваемая подзадача
     * @return созданная подзадача с присвоенным ID
     * @throws IllegalArgumentException если подзадача равна null или эпик с указанным ID не существует
     */
    Subtask createSubtask(Subtask subtask);

    /**
     * Обновляет подзадачу с обработкой изменения epicId.
     * Если эпик подзадачи изменился, обновляет списки подзадач у старого и нового эпиков.
     *
     * @param subtask подзадача с обновлёнными данными
     * @throws IllegalArgumentException если подзадача равна null или подзадача/эпик не существуют
     */
    void updateSubtask(Subtask subtask);

    /**
     * Удаляет подзадачу и обновляет статус её эпика.
     * Также удаляет подзадачу из истории просмотров.
     *
     * @param id идентификатор удаляемой подзадачи
     */
    void deleteSubtask(int id);

    // ========== Дополнительные методы ==========

    /**
     * Возвращает все подзадачи определённого эпика.
     *
     * @param epicId идентификатор эпика
     * @return список подзадач эпика
     * @throws IllegalArgumentException если эпик с указанным ID не существует
     */
    List<Subtask> getEpicSubtasks(int epicId);

    /**
     * Возвращает историю просмотренных задач.
     *
     * @return список просмотренных задач в порядке просмотра
     */
    List<Task> getHistory();
}